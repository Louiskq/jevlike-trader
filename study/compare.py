"""Compare the current decider, a recalibrated current decider and the fine-tuned decider on the
same held-out rows (study/finetune_data.py split), from score files written by study/score.py.

    uv run python study/compare.py --rows data/finetune/rows.jsonl --scores data/finetune/scores \
        --out study/results/finetune.md

"Better than it currently is" (the user's goal, 2026-10-26) is read on the held-out rows as:
lower Brier than the current decider (paired, per row) and than the recalibrated current
decider, with 95% moving-block bootstrap intervals (blocks one horizon long).
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from evaluate import auc_np, bootstrap, running_base  # noqa: E402

from evidence import isotonic_fit, isotonic_predict  # noqa: E402

HORIZON_S = 60.0


def load_scores(path: Path) -> dict[float, float]:
    return {r["t"]: r["p_up"] for r in map(json.loads, open(path))}


def block_len(ts: np.ndarray) -> int:
    gap = float(np.median(np.diff(ts))) if len(ts) > 1 else HORIZON_S
    return max(1, math.ceil(HORIZON_S / max(gap, 1e-9)))


def summarise(name: str, ps: np.ndarray, ys: np.ndarray, base: np.ndarray, block: int) -> dict:
    d = (ps - ys) ** 2 - (base - ys) ** 2
    eps = 1e-6
    ll = -np.mean(ys * np.log(np.clip(ps, eps, 1)) + (1 - ys) * np.log(np.clip(1 - ps, eps, 1)))
    return {
        "name": name, "n": len(ys), "mean_p": float(ps.mean()),
        "brier": float(((ps - ys) ** 2).mean()),
        "log_loss": float(ll), "diff": float(d.mean()),
        "diff_ci": bootstrap(lambda ix: float(d[ix].mean()), len(d), block),
        "auc": auc_np(ps, ys),
        "auc_ci": bootstrap(lambda ix: auc_np(ps[ix], ys[ix]), len(d), block),
    }


def paired(a: np.ndarray, b: np.ndarray, ys: np.ndarray, block: int) -> tuple[float, tuple]:
    """Mean of (Brier of a - Brier of b) per row; negative means a is better."""
    d = (a - ys) ** 2 - (b - ys) ** 2
    return float(d.mean()), bootstrap(lambda ix: float(d[ix].mean()), len(d), block)


def ci(x: tuple, nd: int = 4, sign: bool = True) -> str:
    f = f"{{:+.{nd}f}}" if sign else f"{{:.{nd}f}}"
    return "n/a" if x[0] is None else f"[{f.format(x[0])}, {f.format(x[1])}]"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", default="data/finetune/rows.jsonl")
    ap.add_argument("--scores", default="data/finetune/scores")
    ap.add_argument("--out", default="study/results/finetune.md")
    a = ap.parse_args(argv)
    rows = [json.loads(line) for line in open(a.rows)]
    rows.sort(key=lambda r: r["t"])
    ys_all = np.array([1 - r["gold"] for r in rows], dtype=float)  # 1 = up
    base_all = running_base(ys_all)
    pos = {r["t"]: i for i, r in enumerate(rows)}
    S = Path(a.scores)
    sc = {k: load_scores(S / f"{k}.jsonl") for k in
          ("base_test_context", "base_test_mainnet", "base_train_context", "ft_test_mainnet")
          if (S / f"{k}.jsonl").exists()}
    ts = sorted(set.intersection(*(set(sc[k]) for k in sc if "_test_" in k)))
    idx = np.array([pos[t] for t in ts])
    ys, base = ys_all[idx], base_all[idx]
    block = block_len(np.array(ts))
    fc = {}
    if "base_test_context" in sc:
        fc["Current decider, today's prompt"] = np.array([sc["base_test_context"][t] for t in ts])
    if "base_train_context" in sc and "base_test_context" in sc:
        tr = sorted(sc["base_train_context"])
        model = isotonic_fit([sc["base_train_context"][t] for t in tr],
                             [int(ys_all[pos[t]]) for t in tr])
        fc["Current decider, recalibrated on the train period"] = np.array(
            isotonic_predict(model, list(fc["Current decider, today's prompt"])))
    if "base_test_mainnet" in sc:
        fc["Current decider, prompt with mainnet block"] = np.array(
            [sc["base_test_mainnet"][t] for t in ts])
    if "ft_test_mainnet" in sc:
        fc["Fine-tuned decider, prompt with mainnet block"] = np.array(
            [sc["ft_test_mainnet"][t] for t in ts])
    res = [summarise(k, v, ys, base, block) for k, v in fc.items()]
    lines = [
        "<!-- Generated by study/compare.py. Do not edit. -->",
        "# Fine-tuned decider vs the current one (held-out testnet hours)",
        "",
        f"Held-out rows: {len(ts)} decisions (every 2nd held-out row of study/finetune_data.py, "
        f"about one every {np.median(np.diff(ts)):.0f} s), up rate {ys.mean():.3f}. Question: "
        "will the testnet mid be higher in 60 s. Every model was asked through /decide exactly as "
        "the bot asks. Brier - base rate: negative is better than the running base rate. "
        f"95% moving-block bootstrap, blocks of {block} decisions (60 s).",
        "",
        "| Forecaster | Mean p_up | Brier | Log loss | Brier - base rate [95%] | AUC [95%] |",
        "|---|---|---|---|---|---|",
    ]
    for r in res:
        lines.append(f"| {r['name']} | {r['mean_p']:.3f} | {r['brier']:.4f} | {r['log_loss']:.4f} "
                     f"| {r['diff']:+.4f} {ci(r['diff_ci'])} | {r['auc']:.3f} "
                     f"{ci(r['auc_ci'], 3, False)} |")
    ft = fc.get("Fine-tuned decider, prompt with mainnet block")
    if ft is not None:
        lines += ["", "Paired, per row (fine-tuned Brier minus the other's; negative: fine-tuned "
                  "is better):", "", "| Against | Difference [95%] |", "|---|---|"]
        for k, v in fc.items():
            if v is ft:
                continue
            m, c = paired(ft, v, ys, block)
            lines.append(f"| {k} | {m:+.4f} {ci(c)} |")
    text = "\n".join(lines) + "\n"
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
